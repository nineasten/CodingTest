#   1단계 09-03 - numbers=[3,5,8,10]으로 조건 직접 추적해보기
#   2단계 09-03 - 차집합(set(range(10)) - set(numbers)) 접근
# ─────────────────────────────────────────────────────────


def solution(numbers):

    return sum(set(range(10)) - set(numbers))

print(solution([1,2,3,4,6,7,8,0]))
